		constexpr T abs_value(T x){return x<0?-x:x;}
		template<typename T>
		constexpr T default_epsilon()
		{
			if constexpr(std::numeric_limits<T>::is_integer)return 0;
			else return std::numeric_limits<T>::epsilon()*8;
		}
		template<typename T>
		T cost_tolerance(T c,T x,T y,T eps)
		{
			if constexpr(std::numeric_limits<T>::is_integer)return 0;
			else return eps+std::numeric_limits<T>::epsilon()*16*(abs_value(c)+abs_value(x)+abs_value(y)+1);
		}
